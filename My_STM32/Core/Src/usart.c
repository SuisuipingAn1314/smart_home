// DMA 接收完成回调函数（收到 1 个字节就会进这里）
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if(huart->Instance == USART2)
  {
    uint8_t cmd = rx_data[0]; // 取出数据
    
    if(cmd == 'a')
    {
      // 打开全部 LED
      HAL_GPIO_WritePin(LED2_GPIO_Port, LED2_Pin | LED3_Pin, GPIO_PIN_RESET); // LED2/3 低电平点亮
      HAL_GPIO_WritePin(LED1_GPIO_Port, LED1_Pin, GPIO_PIN_SET);              // LED1 高电平点亮
    }
    else if(cmd == 'b')
    {
      // 关闭全部 LED
      HAL_GPIO_WritePin(LED2_GPIO_Port, LED2_Pin | LED3_Pin, GPIO_PIN_SET);    // LED2/3 高电平熄灭
      HAL_GPIO_WritePin(LED1_GPIO_Port, LED1_Pin, GPIO_PIN_RESET);             // LED1 低电平熄灭
    }
    else if(cmd == 'c')
      HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_4);
    else if(cmd == 'd')
      HAL_TIM_PWM_Stop(&htim4, TIM_CHANNEL_4);
    else if(cmd == 'e')
      HAL_GPIO_WritePin(RELAY_GPIO_Port, RELAY_Pin, GPIO_PIN_SET);
    else if(cmd == 'f')
      HAL_GPIO_WritePin(RELAY_GPIO_Port, RELAY_Pin, GPIO_PIN_RESET);

    // 重新挂载 DMA 接收，等待下一个字节
    HAL_UART_Receive_DMA(&huart2, rx_data, 1);
  }
}
